package dev.zencode.context;

/**
 * 结构化摘要 Prompt 构造（F3.4-F3.6）。
 * <p>
 * 固定 9 个部分组织摘要；首尾各强调一次禁止调用任何工具；
 * 要求先输出分析草稿、再输出正式摘要，草稿用完即弃；
 * 正式摘要包裹在 {@code <summary>} 与 {@code </summary>} 标签之间。
 * </p>
 */
public final class SummaryPrompt {

    private static final String TEXT = """
            你是一名对话压缩助手。请把下面给出的完整历史对话压缩成一份结构化摘要，用于在后续对话中恢复关键上下文。

            严格禁止调用任何工具（包括但不限于 ReadFile、Grep、Bash 等）。你只能基于历史文本生成摘要，不得读取任何文件，不得调用任何外部资源。

            正式摘要必须按以下 9 个固定部分组织，每个部分一个标题，找不到内容的部分写「无」：
            1. 主要请求：用户提出的核心任务与目标
            2. 关键概念：对话中出现的重要概念、术语与定义
            3. 文件代码：涉及的文件路径、代码片段要点（只记录要点，不要臆造不存在的代码）
            4. 错误修复：出现的错误与修复方式
            5. 解决过程：问题解决的关键步骤与结论
            6. 用户原话：关键的用户原始消息原文引用（尽量保留原文措辞）
            7. 待办：尚未完成的事项
            8. 当前工作：压缩时刻正在进行的工作状态
            9. 下一步：后续应继续执行的动作

            输出要求：
            先输出一份分析草稿（对历史的要点梳理），再输出正式摘要。草稿用完即弃，绝不写入后续对话。
            正式摘要必须包裹在 <summary> 与 </summary> 标签之间，除标签外的任何说明文字都不会被采纳。

            再次强调：禁止调用任何工具，禁止读取任何文件。只输出分析草稿与正式摘要文本本身。
            """;

    private SummaryPrompt() {}

    /** 返回固定摘要 System Prompt 文本。 */
    public static String systemPrompt() {
        return TEXT;
    }
}
